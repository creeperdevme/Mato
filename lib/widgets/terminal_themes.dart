TerminalTheme _theme({
  required int background,
  required int foreground,
  required int cursor,
  required List<int> ansi,
  int? selection,
}) {
  assert(ansi.length == 16);
  Color c(int value) => Color(value);
  return TerminalTheme(
    cursor: c(cursor),
    selection: c(selection ?? 0x664D7CFE),
    foreground: c(foreground),
    background: c(background),
    black: c(ansi[0]),
    red: c(ansi[1]),
    green: c(ansi[2]),
    yellow: c(ansi[3]),
    blue: c(ansi[4]),
    magenta: c(ansi[5]),
    cyan: c(ansi[6]),
    white: c(ansi[7]),
    brightBlack: c(ansi[8]),
    brightRed: c(ansi[9]),
    brightGreen: c(ansi[10]),
    brightYellow: c(ansi[11]),
    brightBlue: c(ansi[12]),
    brightMagenta: c(ansi[13]),
    brightCyan: c(ansi[14]),
    brightWhite: c(ansi[15]),
    searchHitBackground: const Color(0xFFFFE066),
    searchHitBackgroundCurrent: const Color(0xFF31FF26),
    searchHitForeground: const Color(0xFF000000),
  );
}

